    Object fromJsonElement(JsonElement f) {
        if (f == null) {
            return null;
        } else if (f.isJsonObject()) {
            return fromJsonObject(f.getAsJsonObject());
        } else if (f.isJsonPrimitive()) {
            System.out.println("PRIMITIVE FOR " + f.getAsJsonPrimitive());
            return null;
        } else if (f.isJsonNull()) {
            return null;
        } else if (f.isJsonArray()) {
            var list = new com.sun.tools.javac.util.ListBuffer<Object>();
            for (JsonElement elem: f.getAsJsonArray()) {
                list.add(fromJsonElement(elem));
            }
            return list.toList();
        } else {
            // ERROR
            return null;
        }
    }

    /** Converts a JsonObject to an element of an OpenJML AST, using the JsonObject's "@class" field 
     * as the type of the target object.
     */
    Object fromJsonObject(JsonObject json) {
        String s = json.get(classTag).getAsJsonPrimitive().getAsString();
        try {
            Class<?> cl = Class.forName(s);
            return gson.fromJson((JsonElement)json,cl);
        } catch (Exception e) {
            var p = json.get(primitiveTag);
            if ("long".equals(s)) {
                return p.getAsJsonPrimitive().getAsLong();
            } else if ("int".equals(s)) {
                return p.getAsJsonPrimitive().getAsInt();
            } if ("boolean".equals(s)) {
                return Boolean.valueOf(p.getAsJsonPrimitive().getAsString());
            } else if ("java.lang.String".equals(s)) {
                return p.isJsonNull() ? null : p.getAsJsonPrimitive().getAsString();
            } else {
                log.error("jml.message","Failed to create an object for a given Json object, with class field \"" + s + "\": " + e);
                System.out.println(json);
                e.printStackTrace(System.out);
                return null;
            }
        }
    }
    
    /** Converts a List<Object> to a List<T> (using unchecked casts of list elements) */
    @SuppressWarnings("unchecked")
    public static <T> List<T> toList(Object list) {
        if (list == null) return null;
        ListBuffer<T> newlist = new ListBuffer<T>();
        for (var elem: (List<Object>)list) newlist.add((T)elem);
        return newlist.toList();
    }
    
    class Adapter<T> implements JsonSerializer<T>, JsonDeserializer<T> {
        /** Retrieves the String[] that is the 'fields' class of the dynamic type of 'this' */
        public String[] fields() { 
            try {
                return (String[])this.getClass().getDeclaredField("fields").get(this);
            } catch (Exception e) {
                log.error("jml.internal", "Failed to find the 'fields' array in class " + this.getClass());
                return new String[0];
            }
        }
        
        /** Returns an array of values, the same length as the 'fields' array, where each returned element is the
         * Object produced by deserializing the corresponding element of the input json object.
         * Most deserializers now use jsonField() instead; this method is retained for JCNewArrayAdapter
         * which needs to loop over the dimAnnotations entries (a List<List<JCAnnotation>>) that cannot
         * be cleanly expressed with a single typed jsonField() call. */
        public Object[] getFieldValues(JsonObject json) {
            var fields = fields();
            var values = new Object[fields.length];
            int i = 0;
            for (var fieldName: fields) {
                try {
                    values[i++] = fromJsonElement(json.get(fieldName));
                } catch (Exception e) {
                    log.error("jml.internal", "Read failure on field: " + fieldName + " in " + this.getClass());
                    values[i++] = null;
                }
            }
            return values;
        }
        
        /** Deserializes a single named field from the JSON object.
         *  If the result is null (field absent or JSON null), checks that the name is
         *  listed in fields[] to distinguish a typo or forgotten field from a legitimate
         *  null value. */
        public Object jsonField(JsonObject json, String name) {
            var value = fromJsonElement(json.get(name));
            if (value == null) {
                boolean found = false;
                for (var f : fields()) {
                    if (f.equals(name)) { found = true; break; }
                }
                if (!found) log.error("jml.internal",
                        "Field '" + name + "' is not listed in fields[] of " + this.getClass().getSimpleName());
            }
            return value;
        }

        /** Type-safe variant of getField: eliminates the unsafe cast at the call site and
         *  reports a clear error if the deserialized value has the wrong type. */
        public <F> F jsonField(JsonObject json, String name, Class<F> type) {
            var value = jsonField(json, name);
            if (value == null) return null;
            if (!type.isInstance(value)) {
                log.error("jml.internal", "Field '" + name + "' in " + this.getClass().getSimpleName()
                        + ": expected " + type.getSimpleName() + " but got " + value.getClass().getSimpleName());
                return null;
            }
            return type.cast(value);
        }

        public void common(JsonElement json, JCTree tree, JsonDeserializationContext context) {
            if (tree instanceof JmlSource ast) {
                JavaFileObject jfo = (JavaFileObject)fromJsonElement(json.getAsJsonObject().get("sourcefile"));
                ast.setSource(jfo);
            }
        }
        
        public void addSymbols(JsonObject obj, T src) {
            JCTree t = (JCTree)src;
            try {
                for (var f: t.getClass().getFields()) { // Only public fields
                    if (Symbol.class.isAssignableFrom(f.getType())) {
                        var value = f.get(t);
                        if (value != null) {
                            //System.out.println("SYMBOL FIELD: " + src.getClass() + " " + f.getName() + " " + f.getType() + " " + value + " " + value.getClass());
                            JsonObject oo = new JsonObject();
                            oo.add(classTag, str(value.getClass()));
                            addId(oo, value);
                            obj.add(f.getName(), oo);
                        }
                    }
                }
            } catch (IllegalAccessException e) {
                System.out.println(e);
            }
        }
        
         /** Default serializing routine for all values of JCTree subclasses */
        public JsonElement serialize(T src, java.lang.reflect.Type type, JsonSerializationContext context) {
            try {
                if (src instanceof JCTree t) {
                    var obj = newgson(t, context);
                    if (includeTypeInfo && src instanceof JCExpression ex) {
                        // Some expressions, such as JCFieldAcess in qualified names, may have null types
                        if (ex.type != null) obj.add("type", str(ex.type.toString()));
                    }
                    if (includeTypeInfo) {
                        addSymbols(obj,src);
                    }

                    for (var s: fields()) {
                        java.lang.reflect.Field f = getField(t.getClass(), s);
                        if (f == null) {
                            // Likely a field name in the 'fields' list that does not agree with the class declaration
                            log.error("jml.internal","Invalid field name " + t.getClass() + " " + s);
                            obj.add(s, context.serialize(null));
                            continue;
                        }
                        Object value = f.get(t);
                        var ft = f.getType();
                        if (ft.isPrimitive() || ft == String.class) {
                            obj.add(s, primitive(ft, value));
                        } else if (IJmlClauseKind.class.isAssignableFrom(ft)) {
                            obj.add(s, primitive(IJmlClauseKind.class, value));
                        } else {
                            obj.add(s, context.serialize(value));
                        }
                    }
                    return obj;
                } else {
                    log.error("jml.internal", "Failure to serialize an input of type " + src.getClass() + " (not a JCTree subclass)");
                }
            } catch (Exception e) {
                log.error("jml.internal", "Failure to serialize an input of type " + src.getClass() + ": " + e);
                e.printStackTrace(System.out);
            }
            return null;
        }
        
        /** Default deserializing routine -- all JCTree subclasses must override this because they each have their own
         * factory method to produce a new AST element. 
         */
        public T deserialize(JsonElement src, java.lang.reflect.Type type, JsonDeserializationContext context) {
            log.error("jml.internal","NO DESERIALIZER: " + this.getClass() + " " + type);
            return null;
        }
    }
    
