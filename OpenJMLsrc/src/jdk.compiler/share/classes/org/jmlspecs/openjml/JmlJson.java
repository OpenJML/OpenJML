/** This class contains custom serializers (for the Gson library), enabling emitting Json representation of a Java/JML AST.
 *  <p>
 *  Generate output Json text using <code>new JmlJson(context).toJson(tree)</code>.
 *  <p>
 *  OpenJDK/OpenJML AST classes contain the information provided by parsing, sufficient to regenerate a source file.
 *  <p>
 *  An OpenJDK AST class contains both fields filled in by parsing and fields whose information is generated by subsequent compiler
 *  phases, such as type attribution. Consequently, we can't just use a generic, reflection-based AST-to-JSON converter.
 *  <p>
 *  Serialization: for serialization we need to state the fields that are to be serialized for each AST class; we also need an Adapter for
 *  each class not derived from JCTree, such as enumerations used for additional information. With that information, Adapter.serialize
 *  can use reflection to generate JSON.
 *  <p>
 *  The relevant fields are listed by name in the 'fields' string for each AST node. This list is used for both serialization and 
 *  deserialization. Although the order of the JSON representation of fields in the output JSON does not matter, they will be output in
 *  the order they are listed in the 'fields ' array. The order is important for deserialization.
 *  <p>
 *  The needed fields could be identified by adding an annotation (e.g. @Expose) to each field. Then Gson could be more directly used.
 *  This would require a lot of source code changes to OpenJDK, but might be more maintainable than the current design.
 *  <p>
 *  Deserialization: AST class creation uses factory methods in JCTree.Factory and JmlTree.JmlFactory, so custom deserializers are needed
 *  for each AST class. Each deserializer calls jsonField(jo, "fieldName", Type.class) to read individual fields by name, then passes
 *  the results to the relevant factory method to create the AST node.
 *  <P>
 *  THERE IS ONE CRUCIALLY IMPORTANT INVARIANT:
 *  <ul>
 *  <li> The 'fields' array for each AST node must contain all the fields that are needed to reconstruct a source code representation of the
 *  node. If a field name is changed in the source code, it must correspondingly be changed in 'fields', or a runtime crash will happen when
 *  writing out such a node. The jsonField() helper validates field names against 'fields' when a null result is returned, catching typos
 *  and missing declarations at the first deserialization.
 *  </ul>
  */

